export type TranslationKey = keyof typeof translations.en;

export function t(lang: Language, key: TranslationKey): string {
  // Typed as a partial record: ku/ar are not statically guaranteed to carry
  // every English key, and the fallback chain below handles any gap. (Was
  // `as any`, which also hid genuine key typos — TODO-023.)
  const dictionary: Partial<Record<TranslationKey, string>> = translations[lang] || translations.en;
  return dictionary[key] || translations.en[key] || key;
}

/**
 * Type-safe level translation resolver.
 * Maps 'beginner', 'intermediate', 'advanced', 'professional' (or 'level_beginner', etc.)
 * to localized labels.
 */
export function tLevel(lang: Language, level: string): string {
  const normalized = level.toLowerCase().replace(/^level_/, '');
  // SAFETY: normalized is constrained to the four level_* suffixes; t() falls back to the key string for anything else.
  const key = `level_${normalized}` as TranslationKey;
  if (key in translations.en) {
    return t(lang, key);
  }
  return level;
}

/**
 * Helper utility to determine UI Layout direction based on active language locale.
 * Essential for correct LTR vs RTL alignment in native layouts.
 */
export function getLayoutDirection(lang: Language): 'rtl' | 'ltr' {
  return lang === 'ar' ? 'rtl' : 'ltr';
}


